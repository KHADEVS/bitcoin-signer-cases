"""Grades each signer's results against the cases and writes results/MATRIX.md.

A signer passes a case when what it does is one of the case's acceptable verdicts and,
whenever it puts a review in front of the user (verdicts "sign" and "warn"), the
amounts on that review are the honest ones. A failed case is graded at the case's
level: "must" for a loss the user cannot see, "should" for weaker protection.

Usage: python report.py
"""

import json
from pathlib import Path

HERE = Path(__file__).parent
AMOUNTS = ("spend", "change", "fee")


def matches(shown, view):
    return all(shown[a] == view[a] for a in AMOUNTS)


def grade(case, result):
    """Returns (passed, reason)."""
    verdict = result["verdict"]
    for alt in case.get("also_safe", []):
        if verdict == alt["verdict"] and matches(result["shown"], alt["view"]):
            return True, ""
    if verdict not in case["acceptable"]:
        return False, "expected %s" % " or ".join(case["acceptable"])
    if verdict in ("sign", "warn"):
        shown, honest = result["shown"], case["honest_view"]
        wrong = [a for a in AMOUNTS if shown[a] != honest[a]]
        if wrong:
            return False, ", ".join("%s shown %s, really %s" % (a, f"{shown[a]:,}", f"{honest[a]:,}") for a in wrong)
    return True, ""


def cell(case, result):
    passed, reason = grade(case, result)
    verdict = result["verdict"]
    if result.get("warnings"):
        verdict += " (" + ", ".join(result["warnings"]) + ")"
    if passed:
        return "pass: " + verdict
    return "**fail (%s)**: %s; %s" % (case["level"], verdict, reason)


def main():
    targets = json.loads((HERE / "results" / "targets.json").read_text(encoding="utf-8"))
    cases = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((HERE / "cases").glob("*.json"))]
    order = {"baseline": 0, "input-amounts": 1, "sighash": 2, "change": 3, "outputs": 4}
    cases.sort(key=lambda c: (order.get(c["class"], 9), c["id"]))
    results = {
        t["name"]: json.loads((HERE / "results" / (t["name"] + ".json")).read_text(encoding="utf-8"))
        for t in targets
    }

    lines = ["# Results", ""]
    lines.append("Generated by `report.py` from `results/*.json`. Do not edit by hand.")
    lines.append("")
    lines.append("| Signer | Code tested |")
    lines.append("| --- | --- |")
    for t in targets:
        lines.append("| %s | %s `%s` (%s), %s |" % (t["name"], t["repo"], t["commit"][:10], t["branch"], t["library"]))
    lines.append("")

    totals = {t["name"]: {"pass": 0, "must": 0, "should": 0} for t in targets}
    header = "| Case | Level | " + " | ".join(t["name"] for t in targets) + " |"
    lines.append(header)
    lines.append("| --- | --- | " + " | ".join("---" for _ in targets) + " |")
    for c in cases:
        row = ["`%s`" % c["id"], c["level"]]
        for t in targets:
            r = results[t["name"]][c["id"]]
            passed, _ = grade(c, r)
            totals[t["name"]]["pass" if passed else c["level"]] += 1
            row.append(cell(c, r))
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    for t in targets:
        n = totals[t["name"]]
        lines.append("- %s: %d of %d pass, %d must-level and %d should-level failures."
                     % (t["name"], n["pass"], len(cases), n["must"], n["should"]))
    lines.append("")

    notes = [t for t in targets if t.get("notes")]
    if notes:
        lines.append("## Notes")
        lines.append("")
        for t in notes:
            for note in t["notes"]:
                lines.append("- %s: %s" % (t["name"], note))
        lines.append("")

    (HERE / "results" / "MATRIX.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
